def write_godot_scene(world_dir: str, world: dict) -> str:
    """Godot 4 scene file (.tscn) referencing imported GLBs."""
    out_dir = os.path.join(world_dir, "export", "godot")
    os.makedirs(out_dir, exist_ok=True)
    lines = ["[gd_scene format=3]", "", "[node name=\"TerminaliaWorld\" type=\"Node3D\"]"]
    n = 0
    for oid, obj in world.get("layout", {}).get("objects", []).items():
        asset_key = obj.get("asset")
        entry = world.get("assets", {}).get(asset_key)
        if not entry:
            continue
        mpp = world.get("terrain", {}).get("meters_per_pixel", 2.0)
        n += 1
        lines += [
            "",
            f"[node name=\"{oid}\" type=\"Node3D\" parent=\".\"]",
            f"transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, "
            f"{obj['pos_xy'][0]*mpp}, 0, {obj['pos_xy'][1]*mpp})",
        ]
    path = os.path.join(out_dir, "world.tscn")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return path
