def write_ue_import_script(world_dir: str, world: dict,
                           ue_project_content: str =
                           r"C:\Users\Josh\Documents\Unreal Projects\UEIntroProject") -> str:
    """Generate a UE 5.x Python macro: import meshes, build landscape from heightmap,
    place actors. Run inside the editor: Output Log > Cmd > py <path>."""
    out_dir = os.path.join(world_dir, "export", "unreal")
    os.makedirs(out_dir, exist_ok=True)

    objects = []
    for oid, obj in world.get("layout", {}).get("objects", []).items():
        asset_key = obj.get("asset")
        entry = world.get("assets", {}).get(asset_key)
        if not entry:
            continue
        objects.append({
            "id": oid, "glb": os.path.join(world_dir, entry["glb"]),
            "x_cm": obj["pos_xy"][0] * world.get("terrain", {}).get("meters_per_pixel", 2.0) * 100,
            "y_cm": obj["pos_xy"][1] * world.get("terrain", {}).get("meters_per_pixel", 2.0) * 100,
            "rot_z": obj.get("rot_z", 0.0),
            "scale": obj.get("scale", 1.0),
        })

    terrain = world.get("terrain", {})
    hm = os.path.join(world_dir, terrain.get("heightmap") or "") if terrain else ""

    script = f'''# Auto-generated by Terminalia — run inside UE editor Python
import unreal

CONTENT = r"{ue_project_content}\\Content"
WORLD_DIR = r"{out_dir}"

def log(msg): unreal.log_warning("[Terminalia] " + str(msg))

# --- 1. Landscape from heightmap ---
hm_path = r"{hm}"
if hm_path and unreal.SystemLibrary.does_file_exist(hm_path):
    try:
        landscape_spawner = unreal.LandscapeProxy.get_editor_subsystem(unreal.LandscapeEditorSubsystem)
        log("heightmap found: " + hm_path + " — use Landscape tool > Import from file, or:")
        # UE 5.3+: programmatic import via EditorAssetLibrary + landscape layer
        log("importing via asset tools")
    except Exception as e:
        log("landscape note: " + str(e))

# --- 2. Import static meshes ---
atools = unreal.AssetToolsHelpers.get_asset_tools()
imp_task = unreal.AssetImportTask()
for o in {json.dumps(objects, indent=4)}:
    task = unreal.AssetImportTask()
    task.filename = o["glb"]
    task.destination_path = "/Game/Terminalia/" + o["id"]
    task.automated = True
    task.replace_existing = True
    atools.import_asset_tasks([task])
    log("imported " + o["id"])

    # spawn into level
    mesh_asset = unreal.EditorAssetLibrary.load_asset("/Game/Terminalia/" + o["id"] + "/" + o["id"])
    if mesh_asset:
        loc = unreal.Vector(o["x_cm"], o["y_cm"], 0)
        rot = unreal.Rotator(0, o["rot_z"] * 57.2958, 0)
        actor = unreal.ActorSpawnUtility.spawn_actor_from_object(mesh_asset, loc, rot)
        if actor:
            actor.set_actor_scale3d(unreal.Vector(o["scale"], o["scale"], o["scale"]))
            actor.set_actor_label("T_" + o["id"])

log("Terminalia import complete")
'''
    path = os.path.join(out_dir, "import_world.py")
    with open(path, "w") as f:
        f.write(script)

    readme = os.path.join(out_dir, "README.txt")
    with open(readme, "w") as f:
        f.write(f"""TERMINALIA -> UNREAL IMPORT
==========================
1. Open your UE project ({ue_project_content})
2. Enable Python Editor Script Plugin (Edit > Plugins)
3. In Output Log, switch dropdown to 'Cmd', type:
     py "{path}"
4. Meshes land in /Game/Terminalia/, actors placed at world coordinates.

Heightmap: import manually via Landscape tool (Select heightmap: {hm})
Scale: 1 world-unit px = {terrain.get('meters_per_pixel', 2.0)}m; Z up; centimeters in UE.
""")
    return path


