def write_unity_editor_script(world_dir: str, world: dict) -> str:
    """C# editor script: drop into Assets/Editor, menu item builds the world."""
    out_dir = os.path.join(world_dir, "export", "unity")
    os.makedirs(out_dir, exist_ok=True)
    objs = []
    for oid, obj in world.get("layout", {}).get("objects", []).items():
        asset_key = obj.get("asset")
        entry = world.get("assets", {}).get(asset_key)
        if not entry:
            continue
        mpp = world.get("terrain", {}).get("meters_per_pixel", 2.0)
        objs.append({
            "id": oid, "glbFile": os.path.basename(entry["glb"]),
            "x": obj["pos_xy"][0] * mpp, "z": obj["pos_xy"][1] * mpp,
            "rotY": obj.get("rot_z", 0.0) * 57.2958,
            "scale": obj.get("scale", 1.0)})

    csharp = f'''// Terminalia world builder — put in Assets/Editor/TerminaliaWorld.cs
// Requires glTFast or UnityGLTF package for .glb import.
using UnityEngine;
using UnityEditor;

public static class TerminaliaWorld {{
    [MenuItem("Terminalia/Build World")]
    public static void Build() {{
        var data = JsonUtility.FromJson<TerminaliaManifest>(
            System.IO.File.ReadAllText("{out_dir}/manifest_unity.json"));
        var root = new GameObject("Terminalia_World");
        foreach (var o in data.objects) {{
            var go = ObjImporter.Import(System.IO.Path.Combine(
                System.IO.Path.GetDirectoryName(data.manifestPath), o.glbFile));
            go.name = "T_" + o.id;
            go.transform.SetParent(root.transform);
            go.transform.localPosition = new Vector3(o.x, 0, o.z);
            go.transform.localRotation = Quaternion.Euler(0, o.rotY, 0);
            go.transform.localScale = Vector3.one * o.scale;
        }}
    }}
}}
'''
    path = os.path.join(out_dir, "TerminaliaWorld.cs")
    with open(path, "w") as f:
        f.write(csharp)
    with open(os.path.join(out_dir, "manifest_unity.json"), "w") as f:
        json.dump({"manifestPath": os.path.join(out_dir, "manifest_unity.json"),
                   "objects": objs}, f, indent=1)
    return path


